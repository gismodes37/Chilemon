"""Behavioral tests for the one-action Windows companion configuration step.

install-companion.bat delegates config placement to companion.install_config so
the logic can be exercised on any OS. These tests pin the observable contract:
find the dashboard-downloaded config, validate it, place it at the default
path, stay idempotent, and fail with actionable guidance when it is missing.

Run with: python -m pytest tests/companion/install_config_test.py -v
"""

from __future__ import annotations

import io
import os
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from companion import install_config as ic  # noqa: E402

DASHBOARD_TOML = '''\
# ChileMon Companion App Configuration
# Auto-generated by ChileMon Dashboard

[asterisk]
host = "192.168.1.50"
port = 4569

[peer]
username = "companion-app"
password = "deadbeefcafebabe"
skip_registration = true

[ws]
bind_host = "127.0.0.1"
bind_port = 9093
'''

EMPTY_PASSWORD_TOML = DASHBOARD_TOML.replace(
    'password = "deadbeefcafebabe"', 'password = ""'
)
MISSING_HOST_TOML = DASHBOARD_TOML.replace('host = "192.168.1.50"', 'host = ""')


def _write(path: Path, text: str) -> Path:
    path.write_text(text, encoding="utf-8")
    return path


def test_resolve_source_prefers_explicit_path(tmp_path: Path) -> None:
    explicit = _write(tmp_path / "custom.toml", DASHBOARD_TOML)
    other = _write(
        tmp_path / ic.DASHBOARD_CONFIG_NAMES[0],
        DASHBOARD_TOML.replace("192.168.1.50", "10.0.0.9"),
    )
    resolved = ic.resolve_source(str(explicit), [tmp_path])
    assert resolved == explicit


def test_resolve_source_finds_dashboard_download(tmp_path: Path) -> None:
    downloaded = _write(
        tmp_path / ic.DASHBOARD_CONFIG_NAMES[0], DASHBOARD_TOML
    )
    assert ic.resolve_source(None, [tmp_path]) == downloaded


def test_resolve_source_returns_none_when_absent(tmp_path: Path) -> None:
    assert ic.resolve_source(None, [tmp_path]) is None


def test_validate_rejects_empty_password(tmp_path: Path) -> None:
    path = _write(tmp_path / "config.toml", EMPTY_PASSWORD_TOML)
    with pytest.raises(ic.ConfigError, match="password"):
        ic.load_and_validate(path)


def test_validate_rejects_missing_host(tmp_path: Path) -> None:
    path = _write(tmp_path / "config.toml", MISSING_HOST_TOML)
    with pytest.raises(ic.ConfigError, match="host"):
        ic.load_and_validate(path)


def test_install_config_copies_dashboard_config_and_is_idempotent(
    tmp_path: Path,
) -> None:
    source = _write(
        tmp_path / ic.DASHBOARD_CONFIG_NAMES[0], DASHBOARD_TOML
    )
    target = tmp_path / "profile" / "config.toml"
    first = ic.install_config(source, target)
    assert first.read_text(encoding="utf-8") == DASHBOARD_TOML
    mtime = first.stat().st_mtime_ns
    second = ic.install_config(source, target)
    assert second == first
    # Identical content is left untouched on a re-run.
    assert second.stat().st_mtime_ns == mtime


def test_install_config_manual_host_secret_renders_valid_toml(
    tmp_path: Path,
) -> None:
    target = tmp_path / "profile" / "config.toml"
    installed = ic.install_config(
        None, target, host="10.0.0.7", secret="abc123"
    )
    parsed = ic.load_and_validate(installed)
    assert parsed["asterisk"]["host"] == "10.0.0.7"
    assert parsed["peer"]["password"] == "abc123"


def test_install_config_without_source_or_credentials_fails_clearly(
    tmp_path: Path,
) -> None:
    with pytest.raises(ic.ConfigError, match="Companion App"):
        ic.install_config(None, tmp_path / "profile" / "config.toml")


def test_cli_returns_nonzero_and_prints_guidance_without_config(
    tmp_path: Path,
) -> None:
    stderr = io.StringIO()
    code = ic.main(
        [
            "--search-dir", str(tmp_path),
            "--target", str(tmp_path / "config.toml"),
        ],
        stderr=stderr,
    )
    assert code == 1
    assert "Companion App" in stderr.getvalue()


@pytest.mark.skipif(os.name == "nt", reason="POSIX mode bits")
def test_target_is_created_with_restricted_mode(tmp_path: Path) -> None:
    source = _write(tmp_path / "config.toml", DASHBOARD_TOML)
    target = tmp_path / "profile" / "config.toml"
    installed = ic.install_config(source, target)
    assert installed.stat().st_mode & 0o777 == 0o600
