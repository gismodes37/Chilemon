<?php
declare(strict_types=1);

/**
 * public/api/companion-download.php
 * -----------------------------------------------
 * Descarga el instalador del Companion con la configuración pre-generada.
 *
 * Flujo:
 *   1. Valida sesión
 *   2. Descubre el host IAX2 desde la request (IP literal del Host, IP LAN detectada
 *      si el Host es un hostname, luego SERVER_ADDR) y el secreto IAX2
 *   3. Genera config.toml con esos valores
 *   4. Rellena la plantilla versionada del instalador .bat y la entrega
 *
 * El .bat baja el código del companion desde GitHub, instala sus dependencias
 * Python y reutiliza los scripts de config/autostart/start del repositorio.
 */

require_once __DIR__ . '/../../config/app.php';
require_once ROOT_PATH . '/app/autoload.php';

use App\Auth\Auth;
use App\Companion\CompanionHost;
use App\Companion\InstallerPayload;

// Validar sesión
Auth::startSession();
if (!Auth::isLoggedIn()) {
    http_response_code(401);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode(['success' => false, 'error' => 'Unauthorized']);
    exit;
}

// Host IAX2 descubierto desde la propia descarga. El instalador es público:
// debe apuntar a la dirección con la que el cliente llegó a este nodo, no a
// una dirección fija guardada en la Pi.
try {
    $pi_ip = CompanionHost::fromRequest($_SERVER);
} catch (\InvalidArgumentException $e) {
    http_response_code(503);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode([
        'success' => false,
        'error'   => 'Could not determine a valid IAX host for this download.',
    ]);
    exit;
}

// Puerto IAX2
$iax_port = 4569;

// Password del peer companion-app — generada en la instalación, nunca hardcodeada.
$secret = defined('IAX_COMPANION_SECRET') ? (string) IAX_COMPANION_SECRET : '';
if ($secret === '') {
    http_response_code(503);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode([
        'success' => false,
        'error'   => 'IAX2 companion secret is not configured. Set iax_companion_secret in config/local.php.',
    ]);
    exit;
}

// Ref del repositorio del cual el instalador descarga el código fuente.
// `main` es el punto de descarga/instalación; puede fijarse a un tag o commit.
$repo_ref = defined('CHILEMON_COMPANION_REF')
    ? (string) constant('CHILEMON_COMPANION_REF')
    : 'main';

// Host estable del nodo: la IP de la request es solo el punto de partida.
// Si el Pi cambia de dirección por DHCP, el Companion usa este nombre como
// candidato adicional (siempre verificado con IAX2) antes de escanear la LAN.
$hostname = trim((string) gethostname());
$node_host = defined('CHILEMON_NODE_HOST')
    ? trim((string) constant('CHILEMON_NODE_HOST'))
    : ($hostname !== ''
        ? (str_ends_with(strtolower($hostname), '.local') ? $hostname : $hostname . '.local')
        : '');
$node_host = preg_replace('/[^A-Za-z0-9._-]/', '', $node_host) ?? '';

// Generar config.toml
$config = <<<TOML
# ChileMon Companion App Configuration
# Auto-generated by ChileMon Dashboard

[asterisk]
host = "{$pi_ip}"
port = {$iax_port}
node_host = "{$node_host}"

[peer]
username = "companion-app"
password = "{$secret}"
skip_registration = true

[audio]
input_device = ""
output_device = ""
sample_rate = 8000
frames_per_buffer = 160

[tx]
idle_rest_s = 120
wake_rms = 0.01
sleep_rms = 0.005
wake_frames = 3
preroll_frames = 10

[ws]
bind_host = "127.0.0.1"
bind_port = 9093

[logging]
level = "INFO"
file = ""

TOML;

// El config se entrega dentro del .bat: escribirlo en /tmp con un nombre
// predecible dejaría el secreto IAX2 legible por otros usuarios.
$template = ROOT_PATH . '/companion/installer-template.bat.tpl';
$payload = (new InstallerPayload($template))->build($config, $repo_ref);

header('Content-Type: application/octet-stream');
header('Content-Disposition: attachment; filename="chilemon-companion-install.bat"');
header('Content-Length: ' . strlen($payload));
echo $payload;
exit;
