#!/usr/bin/env python3
"""Place the dashboard-generated config.toml for the Windows Companion.

install-companion.bat calls this module so config discovery, validation and
placement are testable outside a batch file. The dashboard's **Companion App**
button downloads a .bat installer that embeds the generated config (Pi IP and
random IAX2 companion secret) as base64; the installer decodes it to a staging
file and calls this module, which validates it and copies it to the default
path the companion reads (``~/.chilemon/config.toml``).

An explicit ``--host``/``--secret`` pair is supported as a manual fallback for
operators who know the secret, but the dashboard download is the recommended
path because it never exposes the secret on a command line.

Usage:
    python -m companion.install_config [--config PATH] [--target PATH]
                                       [--search-dir DIR ...]
    python -m companion.install_config --host 192.168.1.50 --secret SECRET
"""

from __future__ import annotations

import argparse
import os
import sys
import tomllib
from pathlib import Path
from typing import Any, Optional, Sequence, TextIO

# The dashboard JS saves the download under this name; "config.toml" is the
# generic name a user may choose when saving manually.
DASHBOARD_CONFIG_NAMES = ("chilemon-companion-config.toml", "config.toml")

_GUIDANCE = (
    "No usable config.toml found. Open the Pi dashboard, click "
    "'Companion App' to download the generated config, then run "
    "install-companion.bat again."
)


class ConfigError(Exception):
    """Raised when a config cannot be found or is missing required values."""


def default_search_dirs() -> list[Path]:
    """Directories searched for a downloaded config, in priority order."""
    return [Path.home() / "Downloads"]


def resolve_source(
    explicit: Optional[str], search_dirs: Sequence[Path]
) -> Optional[Path]:
    """Return the first existing candidate config path.

    An explicit path wins and is returned even when it does not exist, so the
    caller reports a precise error instead of silently falling back.
    """
    if explicit:
        return Path(explicit).expanduser()
    for name in DASHBOARD_CONFIG_NAMES:
        for directory in search_dirs:
            candidate = Path(directory).expanduser() / name
            if candidate.is_file():
                return candidate
    return None


def _toml_string(value: Any) -> str:
    """Escape a value for a double-quoted TOML basic string."""
    return str(value).replace("\\", "\\\\").replace('"', '\\"')


def render_config(host: str, secret: str) -> str:
    """Render a minimal companion config for a manually supplied host/secret."""
    return (
        "# ChileMon Companion App Configuration\n"
        "# Generated by install-companion.bat\n\n"
        "[asterisk]\n"
        f'host = "{_toml_string(host)}"\n'
        "port = 4569\n\n"
        "[peer]\n"
        'username = "companion-app"\n'
        f'password = "{_toml_string(secret)}"\n'
        "skip_registration = true\n\n"
        "[ws]\n"
        'bind_host = "127.0.0.1"\n'
        "bind_port = 9093\n"
    )


def load_and_validate(path: Path) -> dict[str, Any]:
    """Parse and validate a config, returning its TOML data.

    A config is usable only when it has a non-empty ``[asterisk].host`` and a
    non-empty ``[peer].password``. Discovery can learn the Pi IP, but it never
    invents the IAX2 secret, so an empty password is a hard failure.
    """
    try:
        with path.open("rb") as handle:
            data = tomllib.load(handle)
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise ConfigError(f"Could not read {path}: {exc}") from exc

    host = data.get("asterisk", {}).get("host")
    if not isinstance(host, str) or not host.strip():
        raise ConfigError(
            f"{path} has no [asterisk].host. Download the generated config "
            "from the dashboard Companion App button."
        )
    password = data.get("peer", {}).get("password")
    if not isinstance(password, str) or not password.strip():
        raise ConfigError(
            f"{path} has an empty IAX password. Download the generated config "
            "from the dashboard Companion App button."
        )
    return data


def install_config(
    source: Optional[Path],
    target: Path,
    *,
    host: Optional[str] = None,
    secret: Optional[str] = None,
) -> Path:
    """Write a validated config to ``target`` and return the target path.

    Re-running with identical content is a no-op, so the step is idempotent.
    On POSIX the file is created with mode 0600 because it holds the IAX2
    secret. On Windows the file lives under the per-user profile, which already
    inherits user-only ACLs.
    """
    if source is not None:
        load_and_validate(source)
        try:
            content = source.read_text(encoding="utf-8")
        except OSError as exc:
            raise ConfigError(f"Could not read {source}: {exc}") from exc
    elif host and secret:
        content = render_config(host, secret)
    else:
        raise ConfigError(_GUIDANCE)

    target = Path(target).expanduser()
    target.parent.mkdir(parents=True, exist_ok=True)

    if target.is_file() and target.read_text(encoding="utf-8") == content:
        return target

    try:
        target.write_text(content, encoding="utf-8")
        if os.name != "nt":
            target.chmod(0o600)
    except OSError as exc:
        raise ConfigError(f"Could not write {target}: {exc}") from exc
    return target


def main(
    argv: Optional[Sequence[str]] = None,
    *,
    stderr: Optional[TextIO] = None,
    stdout: Optional[TextIO] = None,
) -> int:
    """CLI entry point. Returns a real exit code for the batch wrapper."""
    err = stderr if stderr is not None else sys.stderr
    out = stdout if stdout is not None else sys.stdout
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", help="explicit path to a downloaded config.toml")
    parser.add_argument(
        "--search-dir",
        action="append",
        default=None,
        help="directory to search (repeatable); replaces defaults when given",
    )
    parser.add_argument("--target", help="destination config.toml path")
    parser.add_argument("--host", help="manual fallback: Pi IP or hostname")
    parser.add_argument("--secret", help="manual fallback: IAX companion secret")
    args = parser.parse_args(argv)

    dirs = (
        [Path(p) for p in args.search_dir]
        if args.search_dir
        else default_search_dirs()
    )
    target = (
        Path(args.target).expanduser()
        if args.target
        else Path.home() / ".chilemon" / "config.toml"
    )

    try:
        if args.config:
            source = Path(args.config).expanduser()
        elif args.host or args.secret:
            # Explicit credentials are deliberate: a stale download in the
            # search directories must never silently override them.
            source = None
        else:
            source = resolve_source(None, dirs)
        if source is not None and not source.is_file():
            raise ConfigError(f"Config file not found: {source}")
        installed = install_config(
            source, target, host=args.host, secret=args.secret
        )
    except ConfigError as exc:
        print(f"[ChileMon] ERROR: {exc}", file=err)
        return 1

    print(f"[ChileMon] Companion config installed at {installed}", file=out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
